CREATE TABLE IF NOT EXISTS lumen_recomendacao (
    id_lumen_recomendacao INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aluno INTEGER NOT NULL REFERENCES aluno(id_aluno) ON DELETE CASCADE,
    resultado TEXT NOT NULL,
    data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_lumen_recomendacao_aluno ON lumen_recomendacao (id_aluno, data_criacao DESC);
